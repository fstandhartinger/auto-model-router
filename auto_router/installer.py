# ----------------------------------------------------------------- detection

def key_names(env: dict[str, str]) -> dict[str, bool]:
    """Which known key variables are set. Names only; values are never read out."""
    return {name: bool(env.get(name)) for name in KEY_NAMES}


def probe_local(ports: dict[int, str] = LOCAL_PORTS, timeout: float = 1.5,
                fetch: Callable[[str, float], Any] | None = None) -> list[dict]:
    """OpenAI-compatible servers answering on loopback, with the model ids they list."""
    def _fetch(url: str, t: float) -> Any:
        with urllib.request.urlopen(url, timeout=t) as resp:  # noqa: S310 - loopback only
            return json.load(resp)
    fetch = fetch or _fetch
    found = []
    for port, label in ports.items():
        url = f"http://127.0.0.1:{port}/v1"
        try:
            data = fetch(url + "/models", timeout)
        except Exception:
            continue
        ids = [str(m.get("id")) for m in (data.get("data") or []) if isinstance(m, dict)]
        found.append({"url": url, "port": port, "label": label, "models": ids})
    return found


def match_endpoint(endpoints: list[dict], words: tuple[str, ...]) -> tuple[str, str] | None:
    for ep in endpoints:
        for mid in ep["models"]:
            if any(w in mid.lower() for w in words):
                return ep["url"], mid
    return None


