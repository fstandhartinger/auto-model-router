"""The configuration half of the one-command installers (scripts/install.sh, install.ps1).

The shell scripts fetch the code and build the virtualenv; this module does
everything that needs Python, the same way on every OS:

1. detect the OS, memory and GPU (:mod:`auto_router.hardware`), the installed
   harnesses (:mod:`auto_router.harness`), API keys **by variable name only**,
   and local model servers already running (LM Studio, llama.cpp, Ollama);
2. ask - or take from flags - which model groups and harnesses to set up;
3. write ``~/.auto-router/config.yaml`` (HTTP router) and ``launcher.yaml``
   (route-run and the delegate tool), keys referenced by name;
4. optionally fetch a local model (``--with-bonsai``, ``--with-jev-local``),
   only after showing its size and getting a yes;
5. configure the chosen harnesses, each edit backed up and undoable.

    python -m auto_router.installer --yes --models cloud,jev-local --harness opencode,codex
    python -m auto_router.installer --dry-run --models cloud --harness all
    python -m auto_router.installer --uninstall

It never prints, stores or writes a key value.
"""

