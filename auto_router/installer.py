def plan(args: argparse.Namespace, *, env: dict[str, str], hw_rec: dict, found: dict,
         endpoints: list[dict], asker: Asker, say: Callable[[str], None]) -> dict:
    """Decide groups, harnesses, classifier and local endpoints from flags or answers."""
    keys = key_names(env)
    groups = _split(args.models, GROUPS)
    if groups is None:
        default = ["cloud"] + (["jev-local"] if match_endpoint(endpoints, ("jev", "decider")) else [])
        say("Model groups: cloud = API models on your own keys; subscription = your Claude / ChatGPT "
            "plan through its own CLI (switch mode, route-run, MCP tool); bonsai = Bonsai 2 on this "
            "machine; jev-local = a local open Jev-class decision model for routing.")
        groups = asker.choose("Which model groups?", list(GROUPS), default)
    detected = [h for h, i in found.items() if i["installed"]]
    harnesses = _split(args.harness, harness.HARNESSES)
    if harnesses is None:
        harnesses = asker.choose("Configure which harnesses? (detected ones preselected)",
                                 list(harness.HARNESSES), detected if (asker.interactive or asker.yes) else [])
    gateway = bool(args.claude_gateway)
    if "claude-code" in harnesses and "subscription" in groups and not gateway and asker.interactive:
        gateway = asker.confirm(
            "Also route Claude Code through the local gateway with your own claude.ai login "
            "(ANTHROPIC_BASE_URL)? Own login, own machine only; Anthropic does not support "
            "routing Claude Code to non-Claude models. Switch mode + MCP tool are the default.", False)

    bonsai = jev = None
    if "bonsai" in groups:
        hit = match_endpoint(endpoints, ("bonsai",))
        if hit:
            bonsai = {"url": hit[0], "model": hit[1], "source": "running endpoint"}
    if "jev-local" in groups:
        hit = match_endpoint(endpoints, ("jev", "decider"))
        if hit:
            jev = {"url": hit[0], "model": hit[1], "source": "running endpoint"}
    classifier = args.classifier
    if classifier == "auto":
        classifier = ("jev-local" if "jev-local" in groups else
                      "hosted" if keys.get("TYPESAFE_API_KEY") else "heuristic")
    return {"groups": groups, "harnesses": harnesses, "claude_gateway": gateway, "keys": keys,
            "bonsai": bonsai, "jev": jev, "classifier": classifier}


def _split(value: str | None, allowed: tuple[str, ...]) -> list[str] | None:
    if value is None:
        return None
    items = [x.strip() for x in value.split(",") if x.strip()]
    if items == ["all"]:
        return list(allowed)
    if items == ["none"]:
        return []
    bad = [x for x in items if x not in allowed]
    if bad:
        raise SystemExit(f"unknown value(s) {', '.join(bad)}; choose from {', '.join(allowed)}")
    return items


def fetch_local(kind: str, rec: dict, p: dict, args, asker: Asker, state: Path, os_name: str,
                say: Callable[[str], None]) -> None:
    """--with-bonsai / --with-jev-local: download after a yes, write a start script."""
    if kind == "bonsai":
        pick = rec["bonsai"]
        if not pick.get("fits"):
            say(f"Bonsai 2: not downloaded - {pick['reason']}")
            return
        repo, file, gb, port = pick["repo"], pick["file"], pick["gb"], 8081
        extra = ("Needs the PrismML llama.cpp fork: https://github.com/PrismML-Eng/llama.cpp/releases "
                 "(stock llama.cpp will not load this file).")
        server = "llama-server"
        tail = "-ngl 99 -fa on -c 32768 --temp 1.0 --top-p 0.95 --top-k 20 --min-p 0.05"
    else:
        pick = rec["jev"]
        if not pick.get("id") or not str(pick.get("file", "")).endswith(".gguf"):
            say(f"Jev-class model: nothing to download for this machine ({pick.get('display') or pick.get('reason')}). "
                "Use `--classifier laya` for the in-process Laya fallback.")
            return
        repo, file, gb, port = pick["repo"], pick["file"], pick["gb"], 8082
        extra = "Any recent llama.cpp llama-server works (https://github.com/ggml-org/llama.cpp/releases)."
        server = "llama-server"
        tail = "-c 8192" + (" -ngl 99" if pick["device"] != "cpu" else "")
    say(f"{kind}: {file} from huggingface.co/{repo} is {human_gb(gb)} ({pick.get('licence')}). {extra}")
    if not asker.confirm(f"Download {human_gb(gb)} now?", False):
        say(f"{kind}: not downloaded (confirm interactively or pass --yes)")
        return
    dest = state / "models"
    if args.dry_run:
        say(f"[dry-run] would download {file} to {dest}")
    else:
        download(repo, file, dest, say=say)
    cmd = f"{server} -m \"{dest / file}\" --host 127.0.0.1 --port {port} {tail}"
    write_start_script(state, kind, cmd, os_name, extra, dry_run=args.dry_run, say=say)
    entry = {"url": f"http://127.0.0.1:{port}/v1", "model": file.removesuffix(".gguf"), "source": "downloaded"}
    if kind == "jev-local" and pick.get("id", "").startswith("jevk5-v0.2"):
        entry["temperature"] = 1.532
    p["bonsai" if kind == "bonsai" else "jev"] = entry


def run_install(args: argparse.Namespace, *, env: dict[str, str] | None = None,
                asker: Asker | None = None, endpoints: list[dict] | None = None,
                hw: hardware.Hardware | None = None, which=shutil.which) -> dict:
    env = dict(os.environ if env is None else env)
    lines: list[str] = []

    def say(s: str) -> None:
        lines.append(s)
        if not args.json:
            print(f"  {s}", flush=True)

    ctx = harness.Ctx.from_env(dry_run=args.dry_run, force=args.force, router_url=args.router_url,
                               launcher=args.launcher or "",
                               project=Path(args.project).resolve() if args.project else None,
                               delegate=not args.no_delegate)
    ctx.env, ctx.which = env, which
    if args.home:
        ctx.home = Path(args.home)
        ctx.state_dir = Path(args.state_dir) if args.state_dir else ctx.home / ".auto-router"
    elif args.state_dir:
        ctx.state_dir = Path(args.state_dir)
    if not args.launcher:
        ctx.launcher = ""
        ctx.__post_init__()
    if ctx.os_name == "windows" and not args.no_delegate:
        ctx.delegate = False
        say("Windows: the MCP delegate tool and route-run need POSIX process control; use WSL "
            "for them. The HTTP router and harness provider entries are set up here.")
    state = ctx.state_dir
    src = args.src or str(state / "src")
    asker = asker or Asker(interactive=sys.stdin.isatty() and not args.yes, yes=args.yes)

    hw = hw or hardware.detect()
    rec = hardware.recommend(hw, with_bonsai=True)
    found = harness.detect(ctx, which)
    endpoints = probe_local() if endpoints is None else endpoints
    say(f"system: {hw.os}{' (WSL)' if hw.wsl else ''}, {hw.arch}, RAM {hw.ram_gb} GB, GPU: "
        + (", ".join(f"{g.name} {g.vram_gb} GB" for g in hw.gpus) or "none detected"))
    say("harnesses found: " + (", ".join(h for h, i in found.items() if i["installed"]) or "none"))
    keys = key_names(env)
    say("key variables set: " + (", ".join(k for k, v in keys.items() if v) or "none")
        + "; not set: " + (", ".join(k for k, v in keys.items() if not v) or "none"))
    say("local model servers: " + (", ".join(f"{e['label']} at {e['url']} ({len(e['models'])} models)"
                                             for e in endpoints) or "none running"))

    p = plan(args, env=env, hw_rec=rec, found=found, endpoints=endpoints, asker=asker, say=say)
    say(f"model groups: {', '.join(p['groups']) or 'none'}; harnesses: {', '.join(p['harnesses']) or 'none'}")

    if "bonsai" in p["groups"] and not p["bonsai"]:
        if args.with_bonsai:
            fetch_local("bonsai", rec, p, args, asker, state, ctx.os_name, say)
        else:
            say(f"Bonsai 2: no running endpoint found. {'Fits' if rec['bonsai']['fits'] else 'Does not fit'}: "
                f"{rec['bonsai']['reason']}. Rerun with --with-bonsai to download it, or serve it in LM "
                "Studio / llama-server and rerun.")
    if "jev-local" in p["groups"] and not p["jev"]:
        if args.with_jev_local:
            fetch_local("jev-local", rec, p, args, asker, state, ctx.os_name, say)
        else:
            say(f"Jev-class model: no running endpoint found; picked for this machine: "
                f"{rec['jev'].get('display')} ({rec['jev'].get('device')}). Rerun with --with-jev-local "
                "to download it, or serve it yourself and rerun.")
    if p["classifier"] == "jev-local" and not p["jev"]:
        p["classifier"] = "hosted" if keys.get("TYPESAFE_API_KEY") else "heuristic"
        say(f"classifier: {p['classifier']} until a local Jev-class endpoint is configured")

    config_text = render_config(groups=p["groups"], keys=keys, src=src, bonsai=p["bonsai"], jev=p["jev"],
                                classifier=p["classifier"])
    cfg_path = write_config(state / "config.yaml", config_text, dry_run=args.dry_run, say=say)
    if cfg_path and not args.no_validate:
        err = validate_router_config(cfg_path)
        if err and p["classifier"] == "jev-local":
            say(f"this router version does not accept the local-jev classifier ({err}); "
                "falling back to the heuristic classifier")
            p["classifier"] = "heuristic"
            config_text = render_config(groups=p["groups"], keys=keys, src=src, bonsai=p["bonsai"],
                                        jev=p["jev"], classifier="heuristic")
            cfg_path = write_config(cfg_path, config_text, dry_run=False, say=say)
            err = validate_router_config(cfg_path)
        if err:
            say(f"WARNING: the router could not load {cfg_path}: {err}. Edit it before starting the router.")
    write_config(state / "launcher.yaml", render_launcher(groups=p["groups"], src=src, detected=found),
                 dry_run=args.dry_run, say=say)

    ctx.claude_gateway = p["claude_gateway"]
    results = harness.configure(ctx, p["harnesses"]) if p["harnesses"] else {}
    for line in ctx.log:
        say(line)
    summary = {"groups": p["groups"], "harnesses": results, "classifier": p["classifier"],
               "bonsai": p["bonsai"], "jev": p["jev"], "claude_gateway": p["claude_gateway"],
               "keys_set": [k for k, v in keys.items() if v], "config": str(state / "config.yaml"),
               "hardware": rec, "dry_run": args.dry_run, "log": lines}
    if not args.dry_run:
        (state / "install-summary.json").write_text(json.dumps(summary, indent=2) + "\n", encoding="utf-8")
    return summary


def build_parser() -> argparse.ArgumentParser:
    p = argparse.ArgumentParser(description="Configure the auto router and your coding harnesses.")
    p.add_argument("--yes", "-y", action="store_true", help="no questions; accept downloads you asked for")
    p.add_argument("--models", help=f"comma list of {', '.join(GROUPS)} (or all / none)")
    p.add_argument("--harness", help=f"comma list of {', '.join(harness.HARNESSES)} (or all / none)")
    p.add_argument("--classifier", default="auto", choices=("auto", "jev-local", "hosted", "heuristic", "laya"))
    p.add_argument("--with-bonsai", action="store_true", help="download Bonsai 2 if no endpoint runs (asks first)")
    p.add_argument("--with-jev-local", action="store_true",
                   help="download the picked Jev-class model if no endpoint runs (asks first)")
    p.add_argument("--claude-gateway", action="store_true",
                   help="opt-in: ANTHROPIC_BASE_URL -> local router for Claude Code (own login, own machine)")
    p.add_argument("--project", help="Cursor: project directory for the rule file")
    p.add_argument("--no-delegate", action="store_true", help="skip the MCP delegate tool")
    p.add_argument("--router-url", default="http://127.0.0.1:8787")
    p.add_argument("--launcher", help="path of the auto-router launcher command")
    p.add_argument("--src", help="router source checkout (default ~/.auto-router/src)")
    p.add_argument("--home", help=argparse.SUPPRESS)
    p.add_argument("--state-dir", help=argparse.SUPPRESS)
    p.add_argument("--force", action="store_true", help="replace differing entries (after a backup)")
    p.add_argument("--dry-run", action="store_true", help="print what would change; change nothing")
    p.add_argument("--no-validate", action="store_true", help=argparse.SUPPRESS)
    p.add_argument("--uninstall", action="store_true", help="undo every harness edit this installer made")
    p.add_argument("--json", action="store_true", help="print a JSON summary instead of text")
    return p


def main(argv: list[str] | None = None) -> int:
    args = build_parser().parse_args(argv)
    if args.uninstall:
        ctx = harness.Ctx.from_env(dry_run=args.dry_run)
        if args.home:
            ctx.home = Path(args.home)
            ctx.state_dir = Path(args.state_dir) if args.state_dir else ctx.home / ".auto-router"
        lines = harness.undo(ctx)
        print(json.dumps({"undone": lines}, indent=2) if args.json else
              "\n".join(f"  {l}" for l in lines) or "  nothing to undo")
        return 0
    summary = run_install(args)
    if args.json:
        print(json.dumps({k: v for k, v in summary.items() if k != "log"} | {"log": summary["log"]}, indent=2))
    refused = [h for h, r in summary["harnesses"].items() if isinstance(r, str) and r.startswith("refused")]
    return 3 if refused else 0


if __name__ == "__main__":
    sys.exit(main())
