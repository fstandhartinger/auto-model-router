def write_config(path: Path, text: str, *, dry_run: bool, say: Callable[[str], None]) -> Path | None:
    """Write ``text``; keep a hand-edited file and put the new one beside it."""
    try:
        import yaml
        yaml.safe_load(text)                    # never write a file that does not parse
    except ModuleNotFoundError:
        if not dry_run:
            raise
    if dry_run:
        say(f"[dry-run] would write {path}")
        return None
    path.parent.mkdir(parents=True, exist_ok=True)
    if path.exists():
        old = path.read_text(encoding="utf-8")
        if old == text:
            say(f"{path} unchanged")
            return path
        if not old.startswith(GENERATED):
            new = path.with_name(path.name + ".new")
            new.write_text(text, encoding="utf-8")
            say(f"kept your {path}; the installer's version is {new}")
            return new
        backup = path.with_name(f"{path.name}.auto-router-bak-{time.strftime('%Y%m%dT%H%M%S')}")
        shutil.copy2(path, backup)
        say(f"replaced {path} (it was generated by an earlier run; backup {backup.name})")
    path.write_text(text, encoding="utf-8")
    say(f"wrote {path}")
    return path


def validate_router_config(path: Path) -> str | None:
    """Check the written config against the installed router: the error text, or None.

    Parses the YAML, builds the classifier the policy names (an unknown backend
    raises), and checks every model can get a price. Model prices themselves
    come from the benchmark API when the router starts, so they are not fetched here.
    """
    try:
        import yaml
        raw = yaml.safe_load(path.read_text(encoding="utf-8")) or {}
        from . import jev
        jev.classifier_from_config(raw.get("policy") or {})
        providers = raw.get("providers") or {}
        for m in raw.get("models") or []:
            if m.get("provider") not in providers:
                return f"model {m.get('name')!r} names an unknown provider {m.get('provider')!r}"
            if not (m.get("bench_id") or m.get("prices") or m.get("free") or m.get("subscription")
                    or m.get("capability_like")):
                return f"model {m.get('name')!r} has no price source"
    except Exception as exc:  # the config must not ship broken; report the reason
        return f"{type(exc).__name__}: {exc}"
    return None


# -------------------------------------------------------------- local models

def human_gb(n: float) -> str:
    return f"{n:.2f} GB"


def download(repo: str, file: str, dest: Path, *, run=subprocess.run, which=shutil.which,
             say: Callable[[str], None] = print) -> Path:
    """Fetch one file from Hugging Face: the hf CLI if present, else curl, else urllib."""
    dest.mkdir(parents=True, exist_ok=True)
    target = dest / file
    if target.exists():
        say(f"{target} already present")
        return target
    free = shutil.disk_usage(dest).free
    say(f"free disk at {dest}: {human_gb(free / 1e9)}")
    url = f"https://huggingface.co/{repo}/resolve/main/{file}"
    hf = which("hf") or which("huggingface-cli")
    if hf:
        run([hf, "download", repo, file, "--local-dir", str(dest)], check=True)
    elif which("curl"):
        run(["curl", "-fL", "-C", "-", "-o", str(target) + ".part", url], check=True)
        os.replace(str(target) + ".part", target)
    else:
        urllib.request.urlretrieve(url, str(target) + ".part")  # noqa: S310 - fixed https host
        os.replace(str(target) + ".part", target)
    return target


def write_start_script(state: Path, name: str, command: str, os_name: str, note: str,
                       *, dry_run: bool, say: Callable[[str], None]) -> Path:
    bin_dir = state / "bin"
    if os_name == "windows":
        path = bin_dir / f"start-{name}.cmd"
        text = f"@echo off\r\nrem {note}\r\n{command}\r\n"
    else:
        path = bin_dir / f"start-{name}"
        text = f"#!/bin/sh\n# {note}\nexec {command}\n"
    if dry_run:
        say(f"[dry-run] would write {path}: {command}")
        return path
    bin_dir.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8")
    if os_name != "windows":
        path.chmod(0o755)
    say(f"wrote {path}")
    return path


# ------------------------------------------------------------------ prompts

class Asker:
    def __init__(self, interactive: bool, yes: bool, stream=None):
        self.interactive, self.yes, self.stream = interactive, yes, stream

    def _input(self, prompt: str) -> str:
        if self.stream is not None:
            print(prompt, end="", flush=True)
            return self.stream.readline().strip()
        return input(prompt).strip()

    def confirm(self, question: str, default: bool = False) -> bool:
        if self.yes:
            return True
        if not self.interactive:
            return default
        ans = self._input(f"{question} [{'Y/n' if default else 'y/N'}] ").lower()
        return default if not ans else ans.startswith("y")

    def choose(self, question: str, options: list[str], default: list[str]) -> list[str]:
        if not self.interactive:
            return default
        ans = self._input(f"{question}\n  options: {', '.join(options)}\n  [{','.join(default) or 'none'}] ")
        if not ans:
            return default
        if ans.strip().lower() == "none":
            return []
        return [x.strip() for x in ans.split(",") if x.strip() in options or x.strip() == "all"]


